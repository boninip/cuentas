-- 0016 · Cuentas (DEV): cuenta compartida de dos personas + compensaciones consentidas + reversión (GF-17).
-- Criterios aprobados por Pau el 14/11/2026 (solo DEV; no aprobado para producción): cotejo para DEV con GF-01..16 faltantes anotado;
-- reversión BLOQUEADA si hay movimientos posteriores de los mismos afectados en la misma moneda; doble consumo evitado revalidando al aplicar
-- (la segunda propuesta queda «desactualizada»); ADR-010 separado.
-- Modelo: una compensación es un asiento propio entre las DOS personas de la cuenta compartida (no es un pago): el integrante que debe
-- recibe crédito y el que tiene a favor lo cede, en una sola moneda. Nunca mueve plata. Requiere el consentimiento de ambos.

-- 1) Orden estable de movimientos y nuevos tipos.
alter table cuentas.movements add column seq bigint generated by default as identity;
alter table cuentas.movements drop constraint movements_kind_check;
alter table cuentas.movements drop constraint movements_shape_check;
alter table cuentas.movements add constraint movements_kind_check check (kind in ('expense','payment','payment_confirmation','void','payment_reversal','compensation','compensation_reversal'));
alter table cuentas.movements add constraint movements_shape_check check (
  (kind='expense' and from_user is not null and to_user is null and ref_id is null)
  or (kind in ('payment','compensation') and from_user is not null and to_user is not null and from_user<>to_user and ref_id is null)
  or (kind in ('payment_confirmation','void','payment_reversal','compensation_reversal') and ref_id is not null));

-- 2) Saldos: las compensaciones no revertidas cuentan sin necesidad de confirmación (ya tienen consentimiento de ambos).
create or replace function cuentas.balances_raw(p_group uuid) returns table(user_id uuid, currency text, balance_minor bigint)
language sql stable security definer set search_path='' as $$
 with e as (select m.id,m.currency as cur,m.amount_minor,m.from_user from cuentas.movements m
   where m.group_id=p_group and m.kind='expense' and not exists(select 1 from cuentas.movements v where v.ref_id=m.id and v.kind='void')),
 p as (select m.currency as cur,m.amount_minor,m.from_user,m.to_user from cuentas.movements m
   where m.group_id=p_group and m.kind='payment' and exists(select 1 from cuentas.movements c where c.ref_id=m.id and c.kind='payment_confirmation')
     and not exists(select 1 from cuentas.movements x where x.ref_id=m.id and x.kind='payment_reversal')),
 k as (select m.currency as cur,m.amount_minor,m.from_user,m.to_user from cuentas.movements m
   where m.group_id=p_group and m.kind='compensation'
     and not exists(select 1 from cuentas.movements x where x.ref_id=m.id and x.kind='compensation_reversal')),
 l as (
  select e.from_user as u, e.cur, e.amount_minor as a from e
  union all select s.user_id, e.cur, -s.share_minor from cuentas.movement_shares s join e on e.id=s.movement_id
  union all select p.from_user, p.cur, p.amount_minor from p
  union all select p.to_user, p.cur, -p.amount_minor from p
  union all select k.from_user, k.cur, k.amount_minor from k
  union all select k.to_user, k.cur, -k.amount_minor from k)
 select l.u, l.cur, sum(l.a)::bigint from l group by l.u, l.cur $$;

-- El listado marca también las compensaciones revertidas.
do $m$
declare d text; a text:=$a$v2.kind='payment_reversal'$a$;
begin
 d:=pg_get_functiondef('public.cuentas_movements_list(uuid)'::regprocedure);
 if position(a in d)=0 then raise exception 'patrón movements_list'; end if;
 execute replace(d,a,$b$v2.kind in ('payment_reversal','compensation_reversal')$b$);
end $m$;

-- 3) Cuenta compartida (exactamente dos personas; una abierta por persona y grupo).
create table cuentas.shared_accounts(
 id uuid primary key default gen_random_uuid(),
 group_id uuid not null references cuentas.groups(id),
 member_a uuid not null references auth.users(id),
 member_b uuid not null references auth.users(id),
 status text not null default 'pending' check (status in ('pending','active','rejected','cancelled','unlinked')),
 requested_by uuid not null references auth.users(id),
 created_at timestamptz not null default now(),
 activated_at timestamptz,
 closed_at timestamptz,
 closed_by uuid references auth.users(id),
 check (member_a<member_b),
 check (requested_by in (member_a,member_b))
);
create unique index shared_accounts_open_a on cuentas.shared_accounts(group_id,member_a) where status in ('pending','active');
create unique index shared_accounts_open_b on cuentas.shared_accounts(group_id,member_b) where status in ('pending','active');
create function cuentas.shared_accounts_guard() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.status in ('pending','active') then
  perform pg_advisory_xact_lock(hashtextextended(new.group_id::text,0));
  if exists(select 1 from cuentas.shared_accounts s where s.group_id=new.group_id and s.id<>new.id and s.status in ('pending','active')
            and (s.member_a in (new.member_a,new.member_b) or s.member_b in (new.member_a,new.member_b))) then
   raise exception 'Una de las dos personas ya tiene una cuenta compartida abierta en este grupo';
  end if;
 end if;
 return new;
end $$;
create trigger shared_accounts_guard before insert or update on cuentas.shared_accounts for each row execute function cuentas.shared_accounts_guard();
create trigger shared_accounts_no_delete before delete on cuentas.shared_accounts for each row execute function cuentas.deny_change();
create trigger shared_accounts_no_truncate before truncate on cuentas.shared_accounts for each statement execute function cuentas.deny_change();
alter table cuentas.shared_accounts enable row level security;
revoke all on cuentas.shared_accounts from public, anon, authenticated;
revoke all on function cuentas.shared_accounts_guard() from public, anon, authenticated;

