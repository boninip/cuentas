-- Ayudas internas de disponibilidad (descuentan pagos pendientes de confirmar).
create function cuentas.bal(p_group uuid, p_user uuid, p_cur text) returns bigint language sql stable security definer set search_path='' as $$
 select coalesce((select b.balance_minor from cuentas.balances_raw(p_group) b where b.user_id=p_user and b.currency=p_cur),0) $$;
create function cuentas.debt_avail(p_group uuid, p_user uuid, p_cur text) returns bigint language sql stable security definer set search_path='' as $$
 select greatest(0, greatest(0,-cuentas.bal(p_group,p_user,p_cur)) - coalesce((select sum(m.amount_minor) from cuentas.movements m
   where m.group_id=p_group and m.kind='payment' and m.from_user=p_user and m.currency=p_cur
     and not exists(select 1 from cuentas.movements c where c.ref_id=m.id and c.kind in ('payment_confirmation','payment_reversal'))),0)) $$;
create function cuentas.credit_avail(p_group uuid, p_user uuid, p_cur text) returns bigint language sql stable security definer set search_path='' as $$
 select greatest(0, greatest(0,cuentas.bal(p_group,p_user,p_cur)) - coalesce((select sum(m.amount_minor) from cuentas.movements m
   where m.group_id=p_group and m.kind='payment' and m.to_user=p_user and m.currency=p_cur
     and not exists(select 1 from cuentas.movements c where c.ref_id=m.id and c.kind in ('payment_confirmation','payment_reversal'))),0)) $$;
-- ¿Hay movimientos posteriores de los mismos afectados, en la misma moneda, que dependan de la compensación?
create function cuentas.comp_has_dependents(p_comp uuid) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from cuentas.movements c join cuentas.movements m2 on m2.group_id=c.group_id and m2.seq>c.seq and m2.currency=c.currency
  where c.id=p_comp and m2.kind in ('expense','payment','compensation')
   and not exists(select 1 from cuentas.movements x where x.ref_id=m2.id and x.kind in ('void','payment_reversal','compensation_reversal'))
   and (m2.from_user in (c.from_user,c.to_user) or m2.to_user in (c.from_user,c.to_user)
        or exists(select 1 from cuentas.movement_shares s where s.movement_id=m2.id and s.user_id in (c.from_user,c.to_user)))) $$;
revoke all on function cuentas.bal(uuid,uuid,text), cuentas.debt_avail(uuid,uuid,text), cuentas.credit_avail(uuid,uuid,text), cuentas.comp_has_dependents(uuid) from public, anon, authenticated;

-- apply_proposal ahora devuelve el resultado: 'approved' o 'stale' (desactualizada: no consume nada).
drop function cuentas.apply_proposal(uuid);
create function cuentas.apply_proposal(p_id uuid) returns text
language plpgsql security definer set search_path='' as $$
declare pr cuentas.proposals%rowtype; t cuentas.movements%rowtype; acc cuentas.shared_accounts%rowtype; v_ok boolean:=true;
begin
 select * into pr from cuentas.proposals where id=p_id;
 if pr.kind in ('void_expense','reverse_payment','reverse_compensation') then select * into t from cuentas.movements where id=pr.target_id; end if;
 if pr.kind='void_expense' then
  insert into cuentas.movements(group_id,kind,currency,amount_minor,from_user,description,ref_id,created_by,idempotency_key)
  values(t.group_id,'void',t.currency,t.amount_minor,t.from_user,left(pr.reason,300),t.id,pr.created_by,'void:'||t.id);
 elsif pr.kind='reverse_payment' then
  insert into cuentas.movements(group_id,kind,currency,amount_minor,from_user,to_user,description,ref_id,created_by,idempotency_key)
  values(t.group_id,'payment_reversal',t.currency,t.amount_minor,t.from_user,t.to_user,left(pr.reason,300),t.id,pr.created_by,'reverse:'||t.id);
 elsif pr.kind='compensation' then
  select * into acc from cuentas.shared_accounts where id=pr.account_id;
  if acc.status<>'active' or not cuentas.is_active_member(pr.group_id,pr.debtor) or not cuentas.is_active_member(pr.group_id,pr.creditor)
     or cuentas.debt_avail(pr.group_id,pr.debtor,pr.currency)<pr.amount_minor
     or cuentas.credit_avail(pr.group_id,pr.creditor,pr.currency)<pr.amount_minor then v_ok:=false; end if;
  if v_ok then
   insert into cuentas.movements(group_id,kind,currency,amount_minor,from_user,to_user,description,created_by,idempotency_key)
   values(pr.group_id,'compensation',pr.currency,pr.amount_minor,pr.debtor,pr.creditor,left(pr.reason,300),pr.created_by,'compensation:'||p_id);
  end if;
 else
  if exists(select 1 from cuentas.movements where ref_id=t.id and kind='compensation_reversal') or cuentas.comp_has_dependents(t.id) then v_ok:=false; end if;
  if v_ok then
   insert into cuentas.movements(group_id,kind,currency,amount_minor,from_user,to_user,description,ref_id,created_by,idempotency_key)
   values(t.group_id,'compensation_reversal',t.currency,t.amount_minor,t.from_user,t.to_user,left(pr.reason,300),t.id,pr.created_by,'reverse-comp:'||t.id);
  end if;
 end if;
 if not v_ok then
  update cuentas.proposals set status='stale', resolved_at=now() where id=p_id;
  perform cuentas.log(pr.group_id,pr.created_by,'proposal_stale',jsonb_build_object('proposal',p_id,'kind',pr.kind));
  return 'stale';
 end if;
 update cuentas.proposals set status='approved', resolved_at=now() where id=p_id;
 perform cuentas.log(pr.group_id,pr.created_by,'proposal_applied',jsonb_build_object('proposal',p_id,'kind',pr.kind,'target',pr.target_id));
 return 'approved';
end $$;
revoke all on function cuentas.apply_proposal(uuid) from public, anon, authenticated;

do $m$
declare d text; a text:=$a$if n_ok>=n_req then perform cuentas.apply_proposal(p_proposal); return 'approved'; end if;$a$;
begin
 d:=pg_get_functiondef('public.cuentas_proposal_consent(uuid,text,text)'::regprocedure);
 if position(a in d)=0 then raise exception 'patrón consent'; end if;
 execute replace(d,a,$b$if n_ok>=n_req then return cuentas.apply_proposal(p_proposal); end if;$b$);
end $m$;

-- Listado de propuestas (ahora también compensaciones, que no tienen movimiento objetivo).
create or replace function public.cuentas_proposals_list(p_group uuid) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
 if auth.uid() is null or not cuentas.is_active_member(p_group,auth.uid()) then raise exception 'No autorizado'; end if;
 return coalesce((select jsonb_agg(jsonb_build_object('id',p.id,'kind',p.kind,'target_id',p.target_id,'status',p.status,'version_hash',p.version_hash,'reason',p.reason,
   'created_by',p.created_by,'created_at',p.created_at,'amount_minor',coalesce(t.amount_minor,p.amount_minor),'currency',coalesce(t.currency,p.currency),
   'description',t.description,'debtor',p.debtor,'creditor',p.creditor,'account_id',p.account_id,
   'required',(select jsonb_agg(jsonb_build_object('user_id',r.user_id,'decision',(select c.decision from cuentas.consents c where c.proposal_id=p.id and c.user_id=r.user_id)) order by r.user_id)
               from cuentas.proposal_required r where r.proposal_id=p.id)) order by p.created_at desc)
   from cuentas.proposals p left join cuentas.movements t on t.id=p.target_id where p.group_id=p_group),'[]'::jsonb);
end $$;

-- 5) Funciones públicas de la cuenta compartida.
create function public.cuentas_pair_request(p_group uuid, p_other uuid) returns uuid
language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_status text; v_id uuid;
begin
 if v_user is null then raise exception 'Iniciá sesión'; end if;
 if p_other is null or p_other=v_user then raise exception 'Elegí a otra persona'; end if;
 if not cuentas.is_active_member(p_group,v_user) then raise exception 'No autorizado'; end if;
 select status into v_status from cuentas.groups where id=p_group;
 if v_status='archived' then raise exception 'El grupo está archivado'; end if;
 if not cuentas.is_active_member(p_group,p_other) then raise exception 'La otra persona no es miembro activo del grupo'; end if;
 insert into cuentas.shared_accounts(group_id,member_a,member_b,requested_by) values(p_group,least(v_user,p_other),greatest(v_user,p_other),v_user) returning id into v_id;
 perform cuentas.log(p_group,v_user,'pair_requested',jsonb_build_object('account',v_id));
 return v_id;
end $$;

create function public.cuentas_pair_respond(p_account uuid, p_accept boolean) returns text
language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); a cuentas.shared_accounts%rowtype;
begin
 if v_user is null then raise exception 'Iniciá sesión'; end if;
 select * into a from cuentas.shared_accounts where id=p_account for update;
 if not found or v_user not in (a.member_a,a.member_b) or v_user=a.requested_by then raise exception 'No autorizado'; end if;
 if a.status<>'pending' then raise exception 'La solicitud ya no está pendiente'; end if;
 if not cuentas.is_active_member(a.group_id,a.member_a) or not cuentas.is_active_member(a.group_id,a.member_b) then raise exception 'Las dos personas tienen que ser miembros activos'; end if;
 if p_accept then
  update cuentas.shared_accounts set status='active', activated_at=now() where id=p_account;
  perform cuentas.log(a.group_id,v_user,'pair_activated',jsonb_build_object('account',p_account));
  return 'active';
 end if;
 update cuentas.shared_accounts set status='rejected', closed_at=now(), closed_by=v_user where id=p_account;
 perform cuentas.log(a.group_id,v_user,'pair_rejected',jsonb_build_object('account',p_account));
 return 'rejected';
end $$;

-- Cualquiera de las dos personas se desvincula (o retira su solicitud) sin permiso de la otra; no borra nada.
create function public.cuentas_pair_end(p_account uuid) returns text
language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); a cuentas.shared_accounts%rowtype; v_new text;
begin
 if v_user is null then raise exception 'Iniciá sesión'; end if;
 select * into a from cuentas.shared_accounts where id=p_account for update;
 if not found or v_user not in (a.member_a,a.member_b) then raise exception 'No autorizado'; end if;
 if a.status not in ('pending','active') then return a.status; end if;
 v_new:=case when a.status='pending' then 'cancelled' else 'unlinked' end;
 update cuentas.shared_accounts set status=v_new, closed_at=now(), closed_by=v_user where id=p_account;
 update cuentas.proposals set status='invalidated', resolved_at=now() where account_id=p_account and status='open';
 perform cuentas.log(a.group_id,v_user,'pair_'||v_new,jsonb_build_object('account',p_account));
 return v_new;
end $$;

create function public.cuentas_pairs_list(p_group uuid) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
 if auth.uid() is null or not cuentas.is_active_member(p_group,auth.uid()) then raise exception 'No autorizado'; end if;
 return coalesce((select jsonb_agg(jsonb_build_object('id',s.id,'member_a',s.member_a,'member_b',s.member_b,'status',s.status,'requested_by',s.requested_by,
   'joint',case when s.status='active' then coalesce((select jsonb_agg(jsonb_build_object('currency',c.cur,'a_minor',cuentas.bal(p_group,s.member_a,c.cur),'b_minor',cuentas.bal(p_group,s.member_b,c.cur),
        'joint_minor',cuentas.bal(p_group,s.member_a,c.cur)+cuentas.bal(p_group,s.member_b,c.cur)) order by c.cur)
        from (select distinct b.currency as cur from cuentas.balances_raw(p_group) b where b.user_id in (s.member_a,s.member_b)) c),'[]'::jsonb) else null end)
   order by s.created_at) from cuentas.shared_accounts s where s.group_id=p_group and s.status in ('pending','active')),'[]'::jsonb);
end $$;

-- 6) Compensación y su reversión (siempre por propuesta con consentimiento de las dos personas).
create function public.cuentas_compensation_propose(p_account uuid, p_currency text, p_amount_minor bigint, p_reason text default null) returns uuid
language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); a cuentas.shared_accounts%rowtype; v_status text; deb uuid; cre uuid; v_hash text; v_id uuid; ba bigint; bb bigint;
begin
 if v_user is null then raise exception 'Iniciá sesión'; end if;
 select * into a from cuentas.shared_accounts where id=p_account;
 if not found or v_user not in (a.member_a,a.member_b) then raise exception 'No autorizado'; end if;
 if a.status<>'active' then raise exception 'La cuenta compartida no está activa'; end if;
 if not cuentas.is_active_member(a.group_id,a.member_a) or not cuentas.is_active_member(a.group_id,a.member_b) then raise exception 'Las dos personas tienen que ser miembros activos'; end if;
 select status into v_status from cuentas.groups where id=a.group_id;
 if v_status='archived' then raise exception 'El grupo está archivado'; end if;
 if coalesce(p_currency,'') !~ '^[A-Z]{3}$' or p_amount_minor is null or p_amount_minor<=0 or p_amount_minor>1000000000000 then raise exception 'Importe o moneda inválidos'; end if;
 if coalesce(length(p_reason),0)>300 then raise exception 'Motivo demasiado largo'; end if;
 ba:=cuentas.bal(a.group_id,a.member_a,p_currency); bb:=cuentas.bal(a.group_id,a.member_b,p_currency);
 if ba<0 and bb>0 then deb:=a.member_a; cre:=a.member_b;
 elsif bb<0 and ba>0 then deb:=a.member_b; cre:=a.member_a;
 else raise exception 'No hay una deuda y un saldo a favor entre las dos personas en esa moneda'; end if;
 if p_amount_minor>cuentas.debt_avail(a.group_id,deb,p_currency) or p_amount_minor>cuentas.credit_avail(a.group_id,cre,p_currency) then
  raise exception 'El importe supera lo que se puede compensar ahora (deuda o saldo a favor disponibles)'; end if;
 select id into v_id from cuentas.proposals where kind='compensation' and status='open' and account_id=p_account and currency=p_currency and amount_minor=p_amount_minor and debtor=deb;
 if found then return v_id; end if;
 v_hash:=encode(extensions.digest('compensation|'||p_account::text||'|'||deb::text||'|'||cre::text||'|'||p_amount_minor::text||p_currency||'|'||coalesce(p_reason,''),'sha256'),'hex');
 insert into cuentas.proposals(group_id,kind,version_hash,reason,created_by,account_id,currency,amount_minor,debtor,creditor)
 values(a.group_id,'compensation',v_hash,nullif(trim(coalesce(p_reason,'')),''),v_user,p_account,p_currency,p_amount_minor,deb,cre) returning id into v_id;
 insert into cuentas.proposal_required(proposal_id,user_id) values(v_id,deb),(v_id,cre);
 perform cuentas.log(a.group_id,v_user,'proposal_created',jsonb_build_object('proposal',v_id,'kind','compensation','account',p_account));
 return v_id;
end $$;

create function public.cuentas_compensation_reverse_propose(p_compensation uuid, p_reason text default null) returns uuid
language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); c cuentas.movements%rowtype; v_status text; v_hash text; v_id uuid;
begin
 if v_user is null then raise exception 'Iniciá sesión'; end if;
 select * into c from cuentas.movements where id=p_compensation and kind='compensation';
 if not found or v_user not in (c.from_user,c.to_user) then raise exception 'No autorizado'; end if;
 if not cuentas.is_active_member(c.group_id,c.from_user) or not cuentas.is_active_member(c.group_id,c.to_user) then raise exception 'Las dos personas tienen que ser miembros activos'; end if;
 select status into v_status from cuentas.groups where id=c.group_id;
 if v_status='archived' then raise exception 'El grupo está archivado'; end if;
 if coalesce(length(p_reason),0)>300 then raise exception 'Motivo demasiado largo'; end if;
 if exists(select 1 from cuentas.movements where ref_id=c.id and kind='compensation_reversal') then raise exception 'La compensación ya fue revertida'; end if;
 if cuentas.comp_has_dependents(c.id) then raise exception 'Hay movimientos posteriores de los mismos afectados en esa moneda: resolvelos primero'; end if;
 v_hash:=encode(extensions.digest('reverse_compensation|'||c.id::text||'|'||least(c.from_user,c.to_user)::text||','||greatest(c.from_user,c.to_user)::text||'|'||c.amount_minor::text||c.currency||'|'||coalesce(p_reason,''),'sha256'),'hex');
 insert into cuentas.proposals(group_id,kind,target_id,version_hash,reason,created_by) values(c.group_id,'reverse_compensation',c.id,v_hash,nullif(trim(coalesce(p_reason,'')),''),v_user) returning id into v_id;
 insert into cuentas.proposal_required(proposal_id,user_id) values(v_id,c.from_user),(v_id,c.to_user);
 perform cuentas.log(c.group_id,v_user,'proposal_created',jsonb_build_object('proposal',v_id,'kind','reverse_compensation','target',c.id));
 return v_id;
end $$;

